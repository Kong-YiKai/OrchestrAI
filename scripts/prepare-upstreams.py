"""Build .build/<upstream> from a verified archive + tracked patches + owned overlay.

Order: extract -> patches (upstream edits) -> overlay (owned files) -> remove list.
.build/ is generated: a stale tree created by this script is regenerated automatically;
a directory without our marker is never overwritten.
"""
import argparse
import hashlib
import json
import pathlib
import shutil
import subprocess
import urllib.request
import zipfile

ROOT = pathlib.Path(__file__).resolve().parents[1]
MARKER = '.orchestrai-source'


def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def inputs(spec):
    """Every tracked file that shapes the generated tree, for the freshness stamp."""
    files = [ROOT / p for p in spec.get('patches', [])]
    if 'overlay' in spec:
        files += sorted(p for p in (ROOT / spec['overlay']).rglob('*') if p.is_file())
    return files


def stamp(spec):
    digest = hashlib.sha256(json.dumps(spec, sort_keys=True).encode())
    for path in inputs(spec):
        digest.update(path.relative_to(ROOT).as_posix().encode() + b'\0' + path.read_bytes())
    return digest.hexdigest()


def extract(archive, destination):
    with zipfile.ZipFile(archive) as source:
        for item in source.infolist():
            relative = pathlib.Path(*pathlib.PurePosixPath(item.filename).parts[1:])
            target = (destination / relative).resolve()
            if not target.is_relative_to(destination.resolve()) or (item.external_attr >> 16) & 0o170000 == 0o120000:
                raise ValueError('unsafe archive path or symlink')
            if item.is_dir():
                target.mkdir(parents=True, exist_ok=True)
            else:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(source.read(item))


def customize(spec, destination):
    # Separate Git context avoids silently ignoring paths relative to the parent repo.
    subprocess.run(['git', 'init', '--quiet', str(destination)], check=True)
    for patch in spec.get('patches', []):
        subprocess.run(['git', 'apply', '--check', str(ROOT / patch)], cwd=destination, check=True)
        subprocess.run(['git', 'apply', str(ROOT / patch)], cwd=destination, check=True)
    replaces = spec.get('replaces', {})
    if 'overlay' in spec:
        overlay = ROOT / spec['overlay']
        for source in sorted(p for p in overlay.rglob('*') if p.is_file()):
            relative = source.relative_to(overlay).as_posix()
            target = destination / relative
            if target.exists():
                # Replacing an upstream file must be declared with its upstream hash, so an
                # upstream upgrade fails loudly instead of silently discarding upstream changes.
                if replaces.get(relative) != sha256(target):
                    raise ValueError(f'{relative}: overlay replaces an undeclared or changed upstream file')
            elif relative in replaces:
                raise ValueError(f'{relative}: declared replacement target is missing upstream')
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(source, target)
    for relative in spec.get('remove', []):
        (destination / relative).unlink()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--cache', type=pathlib.Path, help='Directory with <name>-source.zip archives')
    parser.add_argument('--only', help='Prepare one upstream (librechat or rag)')
    args = parser.parse_args()
    lock = json.loads((ROOT / 'deploy/upstreams.json').read_text())
    build = ROOT / '.build'
    build.mkdir(exist_ok=True)
    for name, spec in lock.items():
        if args.only and name != args.only:
            continue
        expected = stamp(spec)
        destination = build / name
        marker = destination / MARKER
        if destination.exists():
            if not marker.is_file():
                raise RuntimeError(f'{destination}: not generated by this script; refusing overwrite')
            if marker.read_text() == expected:
                print(f'{name}: up to date')
                continue
            # Generated directory from an older patch/overlay: rebuild it from scratch.
            shutil.rmtree(destination)
        archive = (args.cache or build) / f'{name}-source.zip'
        if not archive.exists():
            if args.cache:
                raise FileNotFoundError(archive)
            urllib.request.urlretrieve(f"https://codeload.github.com/{spec['repository']}/zip/{spec['commit']}", archive)
        if sha256(archive) != spec['sha256']:
            raise ValueError(f'{name}: source checksum mismatch')
        extract(archive, destination)
        customize(spec, destination)
        marker.write_text(expected)
        print(f'{name}: {spec["commit"]} prepared with source license retained')


if __name__ == '__main__':
    main()
